template<std::size_t N>
std::vector<std::uint16_t> Halves(const std::array<std::uint16_t, N>& bits) {
  return {bits.begin(), bits.end()};
}

Tensor Factor(const std::string& suffix, std::vector<std::uint64_t> dims,
              GgmlType type, const std::vector<std::uint16_t>& bits) {
  return {std::string(kName) + suffix, std::move(dims), type,
          lora_fixture::Bytes(bits)};
}

struct Base {
  std::vector<std::uint8_t> bytes{kBase.begin(), kBase.end()};
  qlora::LoraMatrix matrix{kName, bytes.data(), GgmlType::kQ8_0, kRows, kCols};
};

std::unique_ptr<qlora::LoraAdapter> Open(const std::vector<std::uint8_t>& file,
                                         const qlora::LoraMatrix& target,
                                         std::string* error,
                                         float scale = kScale) {
  return qlora::LoraAdapter::Open(lora_fixture::Read(file), "test.gguf", scale,
                                  "qwen35", {&target, 1}, "the test target",
                                  error);
}

std::vector<std::uint8_t> MergeAll(const qlora::LoraAdapter& adapter) {
  const auto* patch = adapter.Find(kName);
  Check(patch != nullptr, "patch missing");
  std::vector<std::uint8_t> out(patch->target.SizeBytes());
  std::string error;
  Check(adapter.MergeRows(*patch, 0, kRows, out.data(), &error), error);
  return out;
}

template<std::size_t N>
void CheckGolden(GgmlType a_type, const std::vector<std::uint16_t>& a,
                 GgmlType b_type, const std::vector<std::uint16_t>& b,
                 const std::array<std::uint8_t, N>& expected,
                 const std::string& label) {
  Base base;
  const auto file =
      lora_fixture::Adapter("qwen35", kAlpha,
                            {Factor(".lora_a", {kCols, kRank}, a_type, a),
                             Factor(".lora_b", {kRank, kRows}, b_type, b)});
  std::string error;
  const auto adapter = Open(file, base.matrix, &error);
  Check(adapter != nullptr, label + " adapter rejected: " + error);
  const auto merged = MergeAll(*adapter);
  Check(std::equal(merged.begin(), merged.end(), expected.begin(),
                   expected.end()),
        label + " merge differs from the NumPy/gguf-py golden");
}

void CheckFactorTypes() {
  CheckGolden(GgmlType::kF16, Halves(kAF16), GgmlType::kF16, Halves(kBF16),
              kMergedF16, "F16");
  CheckGolden(GgmlType::kBF16, Halves(kABF16), GgmlType::kBF16, Halves(kBBF16),
              kMergedBF16, "BF16");
  CheckGolden(GgmlType::kF16, Halves(kAF16), GgmlType::kBF16, Halves(kBBF16),
              kMergedF16xBF16, "F16 A with BF16 B");

  // F32 B holding exactly the F16 values merges like F16 B.
  std::vector<float> b32;
  for (const auto bits : kBF16) {
    b32.push_back(gufo::quant::Fp16ToFloat(bits));
  }
  Base base;
  const auto file = lora_fixture::Adapter(
      "qwen35", kAlpha,
      {Factor(".lora_a", {kCols, kRank}, GgmlType::kF16, Halves(kAF16)),
       {std::string(kName) + ".lora_b",
        {kRank, kRows},
        GgmlType::kF32,
        lora_fixture::Bytes(b32)}});
  std::string error;
  const auto adapter = Open(file, base.matrix, &error);
  Check(adapter != nullptr, "F16 A with F32 B rejected: " + error);
  const auto merged = MergeAll(*adapter);
  Check(std::equal(merged.begin(), merged.end(), kMergedF16.begin(),
                   kMergedF16.end()),
        "F32 B differs from the same values in F16");

  // Widened F16 factors, subnormals included, are NumPy's float32 casts.
  const auto& a = adapter->Find(kName)->a;
  Check(a.size() == kAF16Widened.size(), "widened A size");
  for (std::size_t i = 0; i < a.size(); ++i) {
    Check(std::bit_cast<std::uint32_t>(a[i]) == kAF16Widened[i],
          "widened F16 element " + std::to_string(i));
  }
  Check(a[5] == 0x1p-24F && a[kCols + 7] == 341 * 0x1p-24F &&
            a[2 * kCols + 11] == -1023 * 0x1p-24F,
        "F16 subnormals widened wrongly");
}

void CheckNonFinite() {
  struct Case {
    GgmlType type;
    std::uint16_t bits;
  };
  for (const auto [type, bits] :
       {Case{GgmlType::kF16, 0x7C00}, Case{GgmlType::kF16, 0xFC00},
        Case{GgmlType::kF16, 0x7E00}, Case{GgmlType::kBF16, 0x7F80},
        Case{GgmlType::kBF16, 0x7FC1}}) {
    auto b = Halves(type == GgmlType::kF16 ? kBF16 : kBBF16);
    b[7] = bits;
    Base base;
    const auto file = lora_fixture::Adapter(
        "qwen35", kAlpha,
        {Factor(".lora_a", {kCols, kRank}, GgmlType::kF16, Halves(kAF16)),
         Factor(".lora_b", {kRank, kRows}, type, b)});
    std::string error;
    Check(Open(file, base.matrix, &error) == nullptr &&
              error ==
                  "LoRA adapter test.gguf: tensor blk.0.ssm_out.weight.lora_b "
                  "has a non-finite value at element 7",
          "non-finite factor " + std::to_string(bits) + ": " + error);
  }
}

void CheckUnsupportedFactor() {
  Base base;
  const auto file = lora_fixture::Adapter(
      "qwen35", kAlpha,
      {{std::string(kName) + ".lora_a",
        {kCols, 1},
        GgmlType::kQ8_0,
        std::vector<std::uint8_t>(34)},
       Factor(".lora_b", {1, kRows}, GgmlType::kF16, {0, 0, 0, 0})});
  std::string error;
  Check(Open(file, base.matrix, &error) == nullptr &&
            error.ends_with("blk.0.ssm_out.weight.lora_a is Q8_0, expected "
                            "F32, F16 or BF16"),
        "Q8_0 factor: " + error);
}

// Rows merge independently: one call over every row and calls over any row
// chunks write the same bytes.
void CheckChunking() {
  constexpr std::uint64_t cols = 96;
  constexpr std::uint64_t rows = 37;
  constexpr std::uint32_t rank = 3;
  std::vector<std::uint8_t> base(rows * cols / 32 * 34);
  for (std::size_t i = 0; i < base.size(); ++i) {
    base[i] = static_cast<std::uint8_t>((i * 131 + 7) % 251);
  }
  // Block scales: small positive halves.
  for (std::size_t block = 0; block < base.size() / 34; ++block) {
    const std::uint16_t d = 0x1800 + static_cast<std::uint16_t>(block % 97);
    std::memcpy(base.data() + block * 34, &d, 2);
  }
  std::vector<std::uint16_t> a(rank * cols);
  std::vector<std::uint16_t> b(rows * rank);
  for (std::size_t i = 0; i < a.size(); ++i) {
    a[i] = static_cast<std::uint16_t>(0x2000 + (i * 37) % 0x0C00) |
           (i % 3 == 0 ? 0x8000 : 0);
  }
  for (std::size_t i = 0; i < b.size(); ++i) {
    b[i] = static_cast<std::uint16_t>(0x3000 + (i * 53) % 0x0C00) |
           (i % 5 == 0 ? 0x8000 : 0);
  }
  const qlora::LoraMatrix target{kName, base.data(), GgmlType::kQ8_0, rows,
                                 cols};
  const auto file = lora_fixture::Adapter(
      "qwen35", kAlpha,
      {Factor(".lora_a", {cols, rank}, GgmlType::kF16, a),
       Factor(".lora_b", {rank, rows}, GgmlType::kF16, b)});
  std::string error;
  const auto adapter = Open(file, target, &error, 1.5F);
  Check(adapter != nullptr, "chunking adapter rejected: " + error);
  const auto* patch = adapter->Find(kName);
  const std::size_t row_bytes = target.RowBytes();
  std::vector<std::uint8_t> whole(target.SizeBytes());
  Check(adapter->MergeRows(*patch, 0, rows, whole.data(), &error), error);
  Check(whole != base, "chunking merge changed nothing");
  for (const std::uint64_t chunk : {1, 2, 5, 16, 36}) {
    std::vector<std::uint8_t> pieces(target.SizeBytes());
    for (std::uint64_t row = 0; row < rows; row += chunk) {
      const std::uint64_t count = std::min(chunk, rows - row);
      Check(adapter->MergeRows(*patch, row, count,
                               pieces.data() + row * row_bytes, &error),
            error);
    }
    Check(pieces == whole, "chunks of " + std::to_string(chunk) +
                               " rows differ from one whole merge");
  }
}

