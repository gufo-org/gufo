void CheckPinnedTrajectory(
    const std::shared_ptr<gufo::models::deepseek_v4_flash::Model>& model) {
  std::string error;
  const auto prompt = model->Tokenize(kTrajectoryPrompt);
  Expect(!prompt.empty(), "trajectory prompt tokenization");

  auto session = model->CreateSession(512, &error);
  Expect(session != nullptr, error);
  Expect(session->Sync(prompt, &error), error);

  int top1_matches = 0;
  std::uint64_t rank_sum = 0;
  int worst_rank = 0;
  for (const int expected_token : kPinnedDs4Trajectory) {
    const auto logits = session->CopyLogits(&error);
    Expect(!logits.empty(), error);
    Expect(expected_token >= 0 &&
               static_cast<std::size_t>(expected_token) < logits.size(),
           "trajectory token range");

    const int selected_token = session->SelectNext(0.0F, nullptr);
    const float expected_logit =
        logits[static_cast<std::size_t>(expected_token)];
    const int rank =
        1 + static_cast<int>(std::count_if(logits.begin(), logits.end(),
                                           [expected_logit](float value) {
                                             return value > expected_logit;
                                           }));
    top1_matches += selected_token == expected_token ? 1 : 0;
    rank_sum += static_cast<std::uint64_t>(rank);
    worst_rank = std::max(worst_rank, rank);

    Expect(session->Evaluate(expected_token, &error), error);
  }

  std::cout << "Pinned DS4 trajectory: top1=" << top1_matches
            << "/128 rank_sum=" << rank_sum << " worst_rank=" << worst_rank
            << '\n';
  Expect(top1_matches >= 116, "128-token top-1 agreement");
  Expect(rank_sum <= 142, "128-token aggregate rank");
  Expect(worst_rank <= 3, "128-token worst rank");
}

void CheckSessionBounds(
    const std::shared_ptr<gufo::models::deepseek_v4_flash::Model>& model) {
  std::string error;
  auto session = model->CreateSession(32, &error);
  Expect(session != nullptr, error);
  Expect(session->PrefillCapacity() > 0 && session->PrefillCapacity() <= 32,
         "prefill allocation fits the session context");
  Expect(session->SelectNext(0.0F, nullptr) == -1 &&
             session->CopyLogits(&error).empty(),
         "uninitialized checkpoint cannot expose logits");
  Expect(!session->Evaluate(1, &error),
         "decode requires initialized target state");
  if (model->HasDspark()) {
    std::vector<int> emitted;
    Expect(!session->DsparkStep(&emitted, &error),
           "DSpark requires initialized target state");
  }
  auto prompt = model->Tokenize(kTrajectoryPrompt);
  prompt.resize(30);
  Expect(session->Sync(prompt, &error), error);
  const auto logits = session->CopyLogits(&error);
  auto invalid = prompt;
  invalid[0] = -1;
  Expect(!session->Sync(invalid, &error) &&
             !session->Evaluate(model->VocabSize(), &error),
         "invalid token IDs are rejected before GPU execution");
  Expect(session->CopyLogits(&error) == logits,
         "argument rejection preserves the valid checkpoint");
  while (session->Position() < session->ContextSize()) {
    Expect(session->Evaluate(session->SelectNext(0.0F, nullptr), &error),
           error.c_str());
  }
  Expect(!session->Evaluate(1, &error) && session->Position() == 32,
         "decode cannot advance past the allocated context");
  if (model->HasDspark()) {
    std::vector<int> emitted;
    Expect(!session->DsparkStep(&emitted, &error) && session->Position() == 32,
           "DSpark fallback cannot overrun a full context");
  }
}

void CheckWidePrefill(
    const std::shared_ptr<gufo::models::deepseek_v4_flash::Model>& model) {
  const auto pattern = model->Tokenize(kTrajectoryPrompt);
  Expect(!pattern.empty(), "wide prefill prompt tokenization");
  std::vector<int> tokens(2048);
  for (std::size_t i = 0; i < tokens.size(); ++i) {
    tokens[i] = pattern[i % pattern.size()];
  }
  const auto run = [&](std::uint32_t context_capacity) {
    std::string error;
    auto session = model->CreateSession(context_capacity, &error);
    Expect(session != nullptr, error);
    Expect(session->Sync(tokens, &error), error);
    std::vector<float> trajectory;
    for (int step = 0; step < 4; ++step) {
      Expect(session->Position() == 2048 + step, "wide prefill frontier");
      const auto logits = session->CopyLogits(&error);
      Expect(!logits.empty(), error);
      Expect(std::all_of(logits.begin(), logits.end(),
                         [](float value) { return std::isfinite(value); }),
             "wide prefill finite logits");
      trajectory.insert(trajectory.end(), logits.begin(), logits.end());
      if (step < 3) {
        Expect(session->Evaluate(session->SelectNext(0.0F, nullptr), &error),
               error.c_str());
      }
    }
    return trajectory;
  };
  const auto reference = run(4096);
  const auto repeat = run(262144);
  Expect(
      reference == repeat,
      "2K prefill and continuation retain exact logits with a 262K capacity");
  const auto* bytes = reinterpret_cast<const std::uint8_t*>(reference.data());
  std::cout << "Wide prefill fingerprint "
            << gufo::crypto::Sha256Hex(
                   std::span(bytes, reference.size() * sizeof(float)))
            << '\n';
}

void CheckBatchedPrefill(
    const std::shared_ptr<gufo::models::deepseek_v4_flash::Model>& model) {
  constexpr int kTrajectoryRepetitions = 2;

  std::string error;
  const auto prompt = model->Tokenize(kTrajectoryPrompt);
  Expect(!prompt.empty(), "prefill prompt tokenization");
  auto tokens = prompt;
  for (int repetition = 0; repetition < kTrajectoryRepetitions; ++repetition) {
    tokens.insert(tokens.end(), kPinnedDs4Trajectory.begin(),
                  kPinnedDs4Trajectory.end());
  }

  auto batched = model->CreateSession(4096, &error);
  Expect(batched != nullptr, error);
  Expect(batched->Sync(tokens, &error), error);
  const auto batched_logits = batched->CopyLogits(&error);
  Expect(!batched_logits.empty(), error);

  auto sequential = model->CreateSession(4096, &error);
  Expect(sequential != nullptr, error);
  Expect(sequential->Sync(prompt, &error), error);
  for (int repetition = 0; repetition < kTrajectoryRepetitions; ++repetition) {
    for (const int token : kPinnedDs4Trajectory) {
      Expect(sequential->Evaluate(token, &error), error);
    }
  }
  const auto sequential_logits = sequential->CopyLogits(&error);
  Expect(sequential_logits.size() == batched_logits.size(),
         "prefill logit shape");

  double squared_error = 0.0;
  double dot = 0.0;
  double batched_norm = 0.0;
  double sequential_norm = 0.0;
  float max_error = 0.0F;
  bool finite = true;
  for (std::size_t index = 0; index < batched_logits.size(); ++index) {
    const float batched_value = batched_logits[index];
    const float sequential_value = sequential_logits[index];
    finite = finite && std::isfinite(batched_value) &&
             std::isfinite(sequential_value);
    const double difference =
        static_cast<double>(batched_value) - sequential_value;
    squared_error += difference * difference;
    dot += static_cast<double>(batched_value) * sequential_value;
    batched_norm += static_cast<double>(batched_value) * batched_value;
    sequential_norm += static_cast<double>(sequential_value) * sequential_value;
    max_error = std::max(max_error, std::abs(batched_value - sequential_value));
  }

  const double rmse =
      std::sqrt(squared_error / static_cast<double>(batched_logits.size()));
  const double denominator = std::sqrt(batched_norm * sequential_norm);
  const double cosine = denominator > std::numeric_limits<double>::min()
                            ? dot / denominator
                            : 0.0;
  const auto batched_top =
      std::max_element(batched_logits.begin(), batched_logits.end());
  const auto sequential_top =
      std::max_element(sequential_logits.begin(), sequential_logits.end());
  const auto batched_top_index = static_cast<std::size_t>(
      std::distance(batched_logits.begin(), batched_top));
  const auto sequential_top_index = static_cast<std::size_t>(
      std::distance(sequential_logits.begin(), sequential_top));
  const float sequential_choice_logit = batched_logits[sequential_top_index];
  const int sequential_choice_rank =
      1 + static_cast<int>(
              std::count_if(batched_logits.begin(), batched_logits.end(),
                            [sequential_choice_logit](float value) {
                              return value > sequential_choice_logit;
                            }));

  std::cout << "Batched prefill (" << tokens.size()
            << " tokens) vs sequential: rmse=" << rmse << " cosine=" << cosine
            << " max_error=" << max_error
            << " top1_match=" << (batched_top_index == sequential_top_index)
            << " sequential_choice_rank=" << sequential_choice_rank << '\n';
  Expect(finite, "prefill finite logits");
  Expect(rmse <= 1.12, "prefill RMSE envelope");
  Expect(cosine >= 0.979, "prefill cosine envelope");
  Expect(max_error <= 5.0F, "prefill maximum error envelope");
  Expect(sequential_choice_rank <= 3, "prefill sequential choice rank");
}

