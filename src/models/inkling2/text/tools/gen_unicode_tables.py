#!/usr/bin/env python3
"""Generates unicode_tables.cpp for the Inkling 2 pre-tokenizer.

Categories needed by the official split pattern: Lu, Lt, Lm, Lo, Ll, M (Mn|Mc|Me),
N (Nd|Nl|No) and White_Space. Usage: gen_unicode_tables.py > unicode_tables.cpp
The tables follow the Unicode version of the running Python (printed in the header).
"""
import sys
import unicodedata

CAT = {"Lu": 1, "Lt": 2, "Lm": 3, "Lo": 4, "Ll": 5, "Mn": 6, "Mc": 6, "Me": 6,
       "Nd": 7, "Nl": 7, "No": 7}
WS = {9, 10, 11, 12, 13, 32, 0x85, 0xA0, 0x1680, *range(0x2000, 0x200B), 0x2028,
      0x2029, 0x202F, 0x205F, 0x3000}

ranges = []  # (start, end, code); code bit 0x80 = white space
for cp in range(0x110000):
    if 0xD800 <= cp <= 0xDFFF:
        continue
    code = CAT.get(unicodedata.category(chr(cp)), 0)
    if cp in WS:
        code |= 0x80
    if code == 0:
        continue
    if ranges and ranges[-1][1] == cp - 1 and ranges[-1][2] == code:
        ranges[-1][1] = cp
    else:
        ranges.append([cp, cp, code])

out = sys.stdout
out.write("// Generated by tools/gen_unicode_tables.py (Unicode %s). Do not edit.\n" % unicodedata.unidata_version)
out.write('#include "text/unicode.hpp"\n\nnamespace inkling2::text::unicode {\n\n')
out.write("const CodepointRange kRanges[] = {\n")
for i, (a, b, c) in enumerate(ranges):
    out.write("{0x%X,0x%X,%d}," % (a, b, c))
    if i % 6 == 5:
        out.write("\n")
out.write("};\nconst std::size_t kRangeCount = %d;\n\n}  // namespace inkling2::text::unicode\n" % len(ranges))
sys.stderr.write("%d ranges, Unicode %s\n" % (len(ranges), unicodedata.unidata_version))
