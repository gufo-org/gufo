// Canonical quantized block layouts. These are the authoritative field
// layouts for the dequant/dot paths. Relocated verbatim from the internal
// definitions in ggml_dequant.cpp so the header is the single source of
// truth; field order and byte sizes match the HIP path
// (src/models/qwen/hip/quant_ops.hpp) and the historical per-file copies
// (models/qwen/state.hpp, tests/). Do NOT redefine block_* locally. Sizes are
// static_asserted; this is the layout contract (see the parity test that
// proves field order against the byte-level spec).
#pragma pack(push, 1)
struct block_q4_K {
  std::uint16_t d;
  std::uint16_t dmin;
  std::uint8_t scales[12];
  std::uint8_t qs[128];
};

struct block_q5_K {
  std::uint16_t d;
  std::uint16_t dmin;
  std::uint8_t scales[12];
  std::uint8_t qh[32];
  std::uint8_t qs[128];
};

struct block_q6_K {
  std::uint8_t ql[128];
  std::uint8_t qh[64];
  std::int8_t scales[16];
  std::uint16_t d;
};

struct block_q3_K {
  std::uint8_t hmask[32];
  std::uint8_t qs[64];
  std::uint8_t scales[12];
  std::uint16_t d;
};

struct block_q8_K {
  float d;
  std::int8_t qs[256];
  std::int16_t bsums[16];
};

// Q8_0: fp16 scale + 32 int8 quantized values (QK=32).
struct block_q8_0 {
  std::uint16_t d;
  std::int8_t qs[32];
};

// IQ4_NL: fp16 scale + 32 non-linear 4-bit codebook indices (QK=32). The
// codebook is kValuesIq4Nl; the index nibble order matches Q4_0 (low nibbles
// give the first 16 elements, high nibbles the second 16).
struct block_iq4_nl {
  std::uint16_t d;
  std::uint8_t qs[16];
};

// IQ4_XS: super-block of 256 with eight 6-bit sub-block scales split across
// scales_h (2 high bits each) and scales_l (4 low bits each), plus 128 bytes
// of packed non-linear 4-bit codebook indices.
struct block_iq4_xs {
  std::uint16_t d;
  std::uint16_t scales_h;
  std::uint8_t scales_l[4];
  std::uint8_t qs[128];
};

// IQ3_S: super-block of 256. Each group of 8 elements indexes the 512-entry
// kIq3sGrid table (8 low bits in qs, 1 high bit in qh) and carries a per-group
// sign byte; scales holds two 4-bit sub-block scales per byte.
struct block_iq3_s {
  std::uint16_t d;
  std::uint8_t qs[64];
  std::uint8_t qh[8];
  std::uint8_t signs[32];
  std::uint8_t scales[4];
};

// IQ3_XXS: super-block of 256 (layout ported from llama.cpp ggml-common.h).
// Each group of 8 elements is two 8-bit indexes into the 256-entry
// kIq3xxsGrid table; the 16 bytes after qs carry one 32-bit word per
// 32-element sub-block: 7 sign bits per group of 8 in bits 0..6 of each byte
// position (7*l) and the sub-block scale (4 bits) in bits 28..31.
struct block_iq3_xxs {
  std::uint16_t d;
  std::uint8_t qs[64];
  std::uint8_t scales_and_signs[16];
};

// IQ2_S: super-block of 256 (layout ported from llama.cpp ggml-common.h).
// Each group of 8 elements indexes the 1024-entry kIq2sGrid table (8 low bits
// in qs, 2 high bits spread over the qh byte of the sub-block); signs carries
// one sign byte per group; scales holds two 4-bit sub-block scales per byte.
struct block_iq2_s {
  std::uint16_t d;
  std::uint8_t qs[64];
  std::uint8_t qh[8];
  std::uint8_t scales[8];
};

// Q2_0: IST-DASLab's 2-bit linear format (block_q2_0 in the llama.cpp fork):
// fp16 scale plus 64 2-bit codes with the mapping 00=-1, 01=0, 10=+1, 11=+2,
// i.e. value = (q - 1) * d. Codes pack four per byte, low bits first.
struct block_q2_0 {
  std::uint16_t d;
  std::uint8_t qs[16];
};
#pragma pack(pop)

