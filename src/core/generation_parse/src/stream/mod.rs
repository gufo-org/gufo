//! A streamed response: the text filter, the tool-call deltas, and the
//! per-piece re-parse that feeds them.

pub mod filter;
pub mod tool_deltas;
pub mod utf8;

use crate::config::{Config, Error, Host};
use crate::events::Sink;
use crate::parse::{emit_final, parse};
use crate::quote::QuoteTracker;
use filter::Filter;
use tool_deltas::ToolDeltas;

/// One streamed generation.
pub struct Stream {
    config: Config,
    filter: Filter,
    tools: ToolDeltas,
    quotes: QuoteTracker,
    /// Finished, or failed: no more input is read.
    done: bool,
}

impl Stream {
    pub fn new(config: Config) -> Self {
        Self {
            filter: Filter::new(&config),
            config,
            tools: ToolDeltas::default(),
            quotes: QuoteTracker::default(),
            done: false,
        }
    }

    /// Reads one piece of generated bytes. Every piece in tool mode re-parses
    /// the whole response, as the C++ parser did.
    pub fn feed(
        &mut self,
        bytes: &[u8],
        host: &mut dyn Host,
        sink: &mut dyn Sink,
    ) -> Result<(), Error> {
        if self.done {
            return Err(Error::Internal);
        }
        // Set first, so a panic inside leaves the handle refusing input.
        self.done = true;
        let result = self.feed_piece(bytes, host, sink);
        self.done = result.is_err();
        result
    }

    fn feed_piece(
        &mut self,
        bytes: &[u8],
        host: &mut dyn Host,
        sink: &mut dyn Sink,
    ) -> Result<(), Error> {
        self.filter.push(bytes, false, &self.config, sink)?;
        if !self.config.buffered && self.filter.in_tools() && self.config.markup.native {
            let generated = parse(
                self.filter.raw(),
                &self.config,
                false,
                true,
                false,
                &mut self.quotes,
                host,
            )?;
            self.tools.update(&generated.calls, sink)?;
        }
        Ok(())
    }

    /// Ends the response: the final parse decides the calls, then the text
    /// tail and the final events follow.
    pub fn finish(
        &mut self,
        enforce_required: bool,
        interrupted: bool,
        host: &mut dyn Host,
        sink: &mut dyn Sink,
    ) -> Result<(), Error> {
        if self.done {
            return Err(Error::Internal);
        }
        self.done = true;
        self.filter.push(&[], true, &self.config, sink)?;
        let generated = parse(
            self.filter.raw(),
            &self.config,
            enforce_required,
            false,
            self.config.track_spans,
            &mut self.quotes,
            host,
        )?;
        self.tools.finish(&generated.calls, interrupted, sink)?;
        self.filter.finish(
            generated.hide_tool_markup,
            &generated.text,
            &generated.reasoning,
            &generated.spans,
            &self.config,
            sink,
        )?;
        emit_final(&generated, sink)
    }
}
